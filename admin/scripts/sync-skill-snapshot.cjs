// Regenerates src/lib/skill/onlineEnglishFeedbackSkill.ts from the Claude plugin skill file, byte for byte.
// Usage: node scripts/sync-skill-snapshot.cjs "<path to online-english-feedback/SKILL.md>"
// The skill itself is never edited; this only copies it so the server-side API call can include it verbatim.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/sync-skill-snapshot.cjs "<path to SKILL.md>"');
  process.exit(1);
}
const text = fs.readFileSync(src, "utf8");
const sha256 = crypto.createHash("sha256").update(Buffer.from(text, "utf8")).digest("hex");
const lines = text.split("\n").length;

const out = `// GENERATED by scripts/sync-skill-snapshot.cjs — DO NOT EDIT BY HAND.
// Verbatim copy of the Claude plugin skill "online-english-feedback" (the source of truth for the English
// feedback rules). The server cannot read the plugin folder at runtime, so the text is embedded here exactly.
// To update: re-run the script against the current SKILL.md; test-evaluationQuality.ts checks the hash.
export const ONLINE_ENGLISH_FEEDBACK_SKILL_META = {
  name: "online-english-feedback",
  lines: ${lines},
  sha256: ${JSON.stringify(sha256)},
} as const;

export const ONLINE_ENGLISH_FEEDBACK_SKILL: string = ${JSON.stringify(text)};
`;
const target = path.join(__dirname, "..", "src", "lib", "skill", "onlineEnglishFeedbackSkill.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)} | lines=${lines} | sha256=${sha256.slice(0, 12)}…`);
